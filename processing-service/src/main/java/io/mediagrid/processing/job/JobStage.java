package io.mediagrid.processing.job;

/** Что делается с файлом сейчас — для отображения хода обработки. */
public enum JobStage {
    /** Получение исходного файла из службы хранения. */
    DOWNLOADING,
    /** Разбор файла: формат, кодеки, длительность, размер кадра. */
    ANALYZING,
    /** Миниатюра и превью. */
    PREVIEW,
    /** Перекодирование в формат, который воспроизводит браузер. */
    TRANSCODING,
    /** Передача результатов в службу хранения. */
    SAVING
}
