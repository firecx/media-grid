-- Удаления, о которых шина ещё не подтвердила событие media.deleted (0.14.0). Строка добавляется в той же
-- транзакции, что и удаление записи, и убирается после подтверждения; оставшиеся досылаются по расписанию.
-- Иначе при недоступной шине файл навсегда остался бы в хранилище.
CREATE TABLE deletion_notices (
    media_id   UUID        PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL
);
