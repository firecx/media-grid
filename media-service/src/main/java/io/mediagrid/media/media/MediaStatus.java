package io.mediagrid.media.media;

/**
 * Жизненный цикл записи о файле.
 * PENDING_UPLOAD → (файл загружен) → UPLOADED → (обработка) → READY или FAILED.
 * Начиная с UPLOADED исходный файл уже доступен: отказ обработки не мешает его просмотру.
 */
public enum MediaStatus {
    /** Запись создана, файл ещё не загружен; видна только владельцу и администратору. */
    PENDING_UPLOAD,
    /** Файл в хранилище, ожидает обработки или обрабатывается. */
    UPLOADED,
    /** Обработка завершена. */
    READY,
    /** Обработка не удалась; исходный файл доступен. */
    FAILED
}
